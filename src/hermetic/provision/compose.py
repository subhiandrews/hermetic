"""Compose files for a service's dependencies, written by code from templates.

The agent decides *what* a service depends on (see `hermetic discover`); it never writes
the file that reaches the Docker daemon. Each kind of dependency has one template here, and the
result goes through the same allowlist as a hand-written file before it is returned.
"""

from __future__ import annotations

import os
import stat
import tempfile
from pathlib import Path
from typing import Any

import yaml

from hermetic.discover.models import Dependency, DependencySet
from hermetic.provision.images import ENGINES
from hermetic.provision.validate import (
    MAX_COMPOSE_BYTES,
    PROJECT_PREFIX,
    ComposeError,
    check_compose,
)

COMPOSE_NAME = "docker-compose.hermetic.yml"
MOCKS_DIR = "mocks"  # under the compose file's directory: WireMock's stubs, one folder each
_PASSWORD = "hermetic"
_HEADER = (
    "# Generated by `hermetic compose` from dependencies.json. Do not edit: run it again.\n"
    "# Engines keep their data in memory, and everything is published on 127.0.0.1 only.\n"
)


class ProvisionError(Exception):
    """There is nothing to provision, or the file could not be written."""


def _service(dependency: Dependency) -> dict[str, Any]:
    engine = ENGINES[dependency.kind]
    service: dict[str, Any] = {"image": engine.image}
    kind = dependency.kind
    if kind == "postgres":
        service["environment"] = {
            "POSTGRES_USER": _PASSWORD,
            "POSTGRES_PASSWORD": _PASSWORD,
            "POSTGRES_DB": _PASSWORD,
        }
        service["tmpfs"] = ["/var/lib/postgresql/data"]
        service["healthcheck"] = _health(["CMD-SHELL", "pg_isready -U hermetic -d hermetic"])
    elif kind == "mysql":
        service["environment"] = {"MYSQL_ROOT_PASSWORD": _PASSWORD, "MYSQL_DATABASE": _PASSWORD}
        service["tmpfs"] = ["/var/lib/mysql"]
        service["healthcheck"] = _health(
            ["CMD", "mysqladmin", "ping", "-h", "127.0.0.1", "-uroot", f"-p{_PASSWORD}"]
        )
    elif kind == "redis":
        service["command"] = ["redis-server", "--save", "", "--appendonly", "no"]
        service["healthcheck"] = _health(["CMD", "redis-cli", "ping"])
    elif kind == "mongo":
        service["tmpfs"] = ["/data/db"]
        service["healthcheck"] = _health(
            ["CMD", "mongosh", "--quiet", "--eval", "db.adminCommand('ping').ok"]
        )
    else:  # http: WireMock, answering from stubs this directory holds
        service["command"] = ["--disable-banner"]
        service["volumes"] = [f"./{MOCKS_DIR}/{dependency.name}:/home/wiremock/mappings:ro"]
    service["ports"] = [f"127.0.0.1::{engine.port}"]
    service["security_opt"] = ["no-new-privileges:true"]
    service["mem_limit"] = engine.memory
    service["pids_limit"] = 512
    service["restart"] = "no"
    return service


def _health(test: list[str]) -> dict[str, Any]:
    return {"test": test, "interval": "2s", "timeout": "3s", "retries": 30}


def generate_compose(dependencies: DependencySet, workdir: Path) -> str:
    """The compose file for the dependencies, in a fixed order so the same set gives the same text.

    `workdir` is the directory the file will sit in; relative mounts are checked against it.
    """
    if not dependencies.dependencies:
        raise ProvisionError("there are no dependencies to provision")
    document = {
        "name": f"{PROJECT_PREFIX}{dependencies.service}",
        "services": {d.name: _service(d) for d in dependencies.dependencies},
    }
    text = _HEADER + yaml.safe_dump(document, sort_keys=False, default_flow_style=False)
    check_compose(text, workdir)  # our own output is held to the same rules as anyone's
    return text


def refuse_links(path: Path) -> None:
    """A repository can commit `.hermetic` as a link; writing through it would land anywhere.

    The folders from the current directory down to the file are checked; for a path elsewhere,
    its own folder is.
    """
    folder = path.parent.absolute()
    try:
        below = folder.relative_to(Path.cwd())
        chain = [Path.cwd().joinpath(*below.parts[: i + 1]) for i in range(len(below.parts))]
    except ValueError:
        chain = [folder]
    for step in chain:
        if step.is_symlink():
            raise ProvisionError(f"{step} is a symlink; not writing through it")


def write_compose(path: Path, text: str) -> None:
    """Save the file whole or not at all, and never through a symlinked folder."""
    refuse_links(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".compose-", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise


def read_compose_file(path: Path) -> str:
    """The text of a compose file, never more than the checker accepts, never through a link."""
    flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0)
    with os.fdopen(os.open(path, flags), "rb") as handle:
        if not stat.S_ISREG(os.fstat(handle.fileno()).st_mode):
            raise ComposeError([f"{path} is not a regular file"])
        raw = handle.read(MAX_COMPOSE_BYTES + 1)
    if len(raw) > MAX_COMPOSE_BYTES:
        raise ComposeError([f"the file is larger than {MAX_COMPOSE_BYTES} bytes"])
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ComposeError(["the file is not valid UTF-8"]) from exc
